#!/usr/bin/env python3
"""Emit a module's explicit-import integration.lisp from gen/derived.json.

Usage: gen-stage2-integration.py GR8S.SECURITY src/security/integration.lisp

Replaces a module's bulk (do-symbols ...) pull with explicit shadowing-imports
of exactly the sibling symbols its source references (per the derived map).
INTERN (not FIND-SYMBOL) is used so forward references to collaborators that
load later in the serial system still resolve -- the owner defines the function
on the interned symbol when it loads.
"""
import json, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
owner = sys.argv[1].upper()
out = pathlib.Path(sys.argv[2])
short = owner.split(".", 1)[1].lower().replace(".", "/") if "." in owner else owner.lower()

d = json.load(open(ROOT / "tools/refactor/gen/derived.json"))
imports = d["imports"].get(owner, {})

def lisp_str(s): return '"' + s + '"'

specs = []
for pkg in sorted(imports.keys()):
    names = sorted(imports[pkg])
    if names:
        specs.append((pkg, names))

L = []
L.append(";;;; SPDX-FileCopyrightText: 2026 Anthony Green")
L.append(";;;; SPDX-License-Identifier: Apache-2.0")
L.append(";;;;")
L.append(f";;;; Explicit cross-module imports for {owner}.")
L.append(";;;;")
L.append(f";;;; {owner} no longer (:use #:gr8s); it imports exactly the sibling symbols")
L.append(";;;; its implementation references.  Loaded after the stage-1 ownership")
L.append(";;;; declarations.  INTERN (not FIND-SYMBOL) forward-declares collaborators that")
L.append(";;;; load later in the serial system; the owner defines onto the same symbol.")
L.append(";;;; Generated by tools/refactor/gen-stage2-integration.py from the derived map.")
L.append("")
L.append(f"(in-package #:{owner.lower()})")
L.append("")
L.append("(eval-when (:compile-toplevel :load-toplevel :execute)")
L.append("  (dolist (spec '(")
for pkg, names in specs:
    row = f"                  ({lisp_str(pkg)}"
    L.append(row)
    line = "                  "
    for n in names:
        tok = " " + lisp_str(n)
        if len(line) + len(tok) > 92:
            L.append(line)
            line = "                  "
        line += tok
    if line.strip():
        L.append(line + ")")
    else:
        L[-1] += ")"
L.append("                  ))")
L.append("    (let ((pkg (find-package (first spec))))")
L.append(f"      (unless pkg (error \"{owner} imports from missing package ~A\" (first spec)))")
L.append("      (dolist (name (rest spec))")
L.append(f"        (shadowing-import (intern name pkg) '#:{owner.lower()})))))")
L.append("")

out.write_text("\n".join(L))
total = sum(len(n) for _, n in specs)
print(f"wrote {out}: {len(specs)} packages, {total} symbols for {owner}")
