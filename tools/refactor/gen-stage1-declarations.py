#!/usr/bin/env python3
"""Generate src/refactor/stage1-declarations.lisp from gen/stage1-rehome.sexp.

For every symbol currently homed in GR8S but owned (by source) by a module
package, intern it in the owner package and shadowing-import it into GR8S, so
the owner becomes the symbol's home while un-migrated callers keep reaching it
through GR8S::NAME.  This is the generalization of foundation/declarations.lisp
to every remaining owner.  GR8S.FOUNDATION is handled separately (it is consumed
earlier in load order), so it is excluded here.

Facade-exported names (the ones in GR8S's public :export) are additionally
re-exported from GR8S after the shadowing-import, since shadowing-import does not
preserve external status.
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SEXP = ROOT / "tools/refactor/gen/stage1-rehome.sexp"
OUT = ROOT / "src/refactor/stage1-declarations.lisp"

# The 36 facade-exported names that are re-homed (from the facade-overlap probe).
FACADE_EXPORTED = {
 "+GR8S-VERSION+","ALLOCATE-NODE-POD-CIDR","ALLOCATE-NODE-POD-CIDRS",
 "CLUSTER-PKI-CA-CERTIFICATE-PATH","CLUSTER-PKI-CA-FINGERPRINT",
 "CLUSTER-PKI-CA-PRIVATE-KEY-PATH","CREATE-JOIN-TOKEN","CRI-CONTAINER-INFO-EXIT-CODE",
 "CRI-CONTAINER-INFO-STATE","CRI-VERSION-INFO-RUNTIME-API-VERSION",
 "CRI-VERSION-INFO-RUNTIME-NAME","CRI-VERSION-INFO-RUNTIME-VERSION",
 "CRI-VERSION-INFO-VERSION","ENROLL-NODE-CSR","ENROLL-NODE-OVER-GRPC",
 "EXPIRE-NODE-HEARTBEATS","GENERATE-NODE-KEY-AND-CSR","GET-NODE","LIST-NODES",
 "MARK-NODE-NOT-READY","MARK-NODE-READY","PARSE-POD","PKI-ERROR","PKI-ERROR-REASON",
 "POD-SCHEDULING-PHASE","RECONCILE-ALL","RECONCILER-LOGS","REGISTER-NODE",
 "START-RECONCILIATION-WORKER","STOP-RECONCILIATION-WORKER",
 "UNSUPPORTED-NODE-PROTOCOL-VERSION","UNSUPPORTED-NODE-PROTOCOL-VERSION-RECEIVED",
 "UNSUPPORTED-NODE-PROTOCOL-VERSION-SUPPORTED","UPDATE-POD-OBSERVED-PHASE",
 "VERIFY-NODE-CERTIFICATE","WRITE-KUBECONFIG",
}

data = SEXP.read_text()
groups = []  # (owner, [names])
for m in re.finditer(r':owner "([^"]+)" :names\s*\(([^)]*)\)', data):
    owner = m.group(1)
    names = re.findall(r'"([^"]+)"', m.group(2))
    if owner in ("GR8S.FOUNDATION", "GR8S.RUNTIME.CONTAINERD", "GR8S.PROTOCOL"):
        # FOUNDATION is handled in foundation/declarations.lisp (loaded earlier).
        # RUNTIME.CONTAINERD owns its symbols via runtime/containerd/package.lisp,
        # which is loaded AFTER this file, so its package does not yet exist here.
        # PROTOCOL defines its symbols (e.g. the UNSUPPORTED-NODE-PROTOCOL-VERSION
        # condition) in protocol/node-protocol.lisp, which loads BEFORE this file;
        # re-homing after the fact would orphan the condition class, so those
        # symbols are owned natively via protocol/package.lisp's shadow/export.
        continue
    groups.append((owner, names))

def lisp_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

lines = []
lines.append(";;;; SPDX-FileCopyrightText: 2026 Anthony Green")
lines.append(";;;; SPDX-License-Identifier: Apache-2.0")
lines.append(";;;;")
lines.append(";;;; GENERATED by tools/refactor/gen-stage1-declarations.py -- do not edit by hand.")
lines.append(";;;;")
lines.append(";;;; Re-home every symbol that is still interned in GR8S but whose source lives in")
lines.append(";;;; a module: intern it in its owner package and shadowing-import it into GR8S.")
lines.append(";;;; The owner becomes the symbol's home; GR8S keeps it so un-migrated callers'")
lines.append(";;;; GR8S::NAME references keep resolving, and the implementation files (whether")
lines.append(";;;; (in-package #:gr8s) or (in-package #:gr8s.<module>)) then define onto the")
lines.append(";;;; owner's symbol.  Loaded immediately after the module package definitions and")
lines.append(";;;; before any implementation file.  GR8S.FOUNDATION is handled earlier, in")
lines.append(";;;; src/foundation/declarations.lisp.  Temporary: removed once the facade is gone.")
lines.append("")
lines.append("(in-package #:cl-user)")
lines.append("")
lines.append("(eval-when (:compile-toplevel :load-toplevel :execute)")
lines.append("  (let ((g (find-package '#:gr8s)))")
lines.append("    (dolist (spec")
lines.append("        '(")
for owner, names in groups:
    lines.append(f"          ({lisp_str(owner)}")
    # chunk names for readability
    row = "           "
    for n in names:
        tok = " " + lisp_str(n)
        if len(row) + len(tok) > 95:
            lines.append(row)
            row = "           "
        row += tok
    if row.strip():
        lines.append(row)
    lines.append("           )")
lines.append("          ))")
lines.append("      (let ((owner (find-package (first spec))))")
lines.append("        (unless owner (error \"missing owner package ~A\" (first spec)))")
lines.append("        (dolist (name (rest spec))")
lines.append("          (let ((s (find-symbol name owner)))")
lines.append("            ;; Ensure an OWNER-homed symbol: if NAME is absent, intern creates")
lines.append("            ;; it; if it is only inherited (e.g. a GR8S facade export reached")
lines.append("            ;; through :use #:gr8s) or imported, shadow detaches it first.")
lines.append("            (unless (and s (eq (symbol-package s) owner))")
lines.append("              (when s (shadow name owner))")
lines.append("              (setf s (intern name owner)))")
lines.append("            ;; Mirror the owner's binding into the GR8S facade.")
lines.append("            (shadowing-import s g)")
exported = sorted(FACADE_EXPORTED)
lines.append(f"            (when (member name '({' '.join(lisp_str(n) for n in exported)})")
lines.append("                          :test #'string=)")
lines.append("              (export s g))))))))")
lines.append("")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines))
total = sum(len(n) for _, n in groups)
print(f"wrote {OUT} : {len(groups)} owners, {total} symbols")
